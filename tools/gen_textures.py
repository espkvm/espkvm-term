#!/usr/bin/env python3
"""Makes the button texture (worn safety-yellow paint) as a tileable RGB565
LVGL image in main/textures.c. Screen-size surfaces are drawn on the device
(main/texgen.c), so they never repeat. Needs numpy (and Pillow
for --preview). Same seed, same pictures."""
import sys
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parent.parent / 'main' / 'textures.c'
rng = np.random.default_rng(7)


def noise(n, scale):
    """Tileable noise: random spectrum, low-passed. 0..1."""
    f = np.fft.fft2(rng.standard_normal((n, n)))
    k = np.fft.fftfreq(n)
    r = np.sqrt(k[:, None] ** 2 + k[None, :] ** 2)
    f *= np.exp(-(r * n / scale) ** 2)
    v = np.real(np.fft.ifft2(f))
    return (v - v.min()) / (v.max() - v.min())


def scratches(n, count, length, width=1.0):
    """Thin straight-ish lines that wrap around the tile. 0..1 coverage."""
    m = np.zeros((n, n))
    for _ in range(count):
        x, y = rng.uniform(0, n, 2)
        a = rng.normal(0.35, 0.5)  # mostly one direction, like wear
        L = rng.uniform(0.3, 1.0) * length
        s = rng.uniform(0.3, 1.0)
        for t in np.linspace(0, L, int(L * 2)):
            px, py = int(x + t * np.cos(a)) % n, int(y + t * np.sin(a)) % n
            m[py, px] = max(m[py, px], s)
            if width > 1:
                m[(py + 1) % n, px] = max(m[(py + 1) % n, px], s * 0.5)
    return m


def chips(n, density, size):
    """Paint chipped off: blobs where the noise is high."""
    v = noise(n, size) * 0.75 + noise(n, size * 5) * 0.25  # ragged edges
    return np.clip((v - np.quantile(v, 1 - density)) / 0.02, 0, 1)


def worn_yellow(n=256):
    base = np.array([242, 182, 0], float)
    mott = noise(n, 6) * 0.6 + noise(n, 30) * 0.4
    img = base[None, None, :] * (0.86 + 0.16 * mott[..., None])
    grime = noise(n, 3)
    img *= (1 - 0.18 * np.clip(grime - 0.5, 0, 1)[..., None] * 2)
    sc = scratches(n, 70, 60)
    img = img * (1 - 0.35 * sc[..., None]) + 255 * 0.12 * sc[..., None]
    ch = chips(n, 0.035, 14)
    metal = np.array([58, 56, 52], float) * (0.8 + 0.4 * noise(n, 40))[..., None]
    img = img * (1 - ch[..., None]) + metal * ch[..., None]
    return np.clip(img, 0, 255)


def dark_metal(n=256):
    base = np.array([30, 31, 33], float)
    # brushed: noise stretched along x
    br = np.repeat(noise(n, 60)[:, :1], n, axis=1) * 0.5 + noise(n, 50) * 0.5
    img = base[None, None, :] * (0.85 + 0.3 * br[..., None])
    img += 10 * (noise(n, 4) - 0.5)[..., None]
    sc = scratches(n, 50, 50)
    img += 26 * sc[..., None]
    return np.clip(img, 0, 255)


def hazard(n=64, period=32):
    y, x = np.mgrid[0:n, 0:n]
    stripe = ((x + y) % period) < period // 2
    yel = worn_yellow(n * 4)[:n, :n]  # reuse the paint
    blk = np.array([22, 22, 22], float)[None, None, :] * (0.9 + 0.3 * noise(n, 8))[..., None]
    img = np.where(stripe[..., None], yel, blk)
    return np.clip(img, 0, 255)


def rgb565(img):
    a = img.astype(np.uint16)
    v = ((a[..., 0] >> 3) << 11) | ((a[..., 1] >> 2) << 5) | (a[..., 2] >> 3)
    return v.astype('<u2').tobytes()


def c_image(name, img):
    h, w, _ = img.shape
    data = rgb565(img)
    rows = []
    for i in range(0, len(data), 24):
        rows.append('    ' + ','.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',')
    return (f'static const uint8_t {name}_map[] = {{\n' + '\n'.join(rows) + '\n};\n\n'
            f'const lv_image_dsc_t {name} = {{\n'
            f'    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,\n'
            f'               .w = {w}, .h = {h}, .stride = {w * 2}}},\n'
            f'    .data_size = sizeof({name}_map),\n'
            f'    .data = {name}_map,\n}};\n')


def main():
    imgs = {'tex_yellow': worn_yellow()}
    if '--preview' in sys.argv:
        from PIL import Image
        for k, v in imgs.items():
            t = np.tile(v, (2, 2, 1)).astype(np.uint8)
            Image.fromarray(t).save(sys.argv[-1] + f'/{k}.png')
        return
    body = '\n'.join(c_image(k, v) for k, v in imgs.items())
    OUT.write_text('/* Generated by tools/gen_textures.py - do not edit. */\n'
                   '#include "lvgl.h"\n\n' + body)
    print(OUT)


main()
